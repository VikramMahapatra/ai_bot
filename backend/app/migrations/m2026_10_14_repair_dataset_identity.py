"""Repair only an owned dataset ID missing both a default and an identity.

Existing serial/identity columns and all stored IDs are left untouched. The
caller owns the transaction; SQLite needs no repair and ignores ORM Identity.
"""
from sqlalchemy import text
from sqlalchemy.engine import Connection

MIGRATION_ID = "2026_10_14_repair_dataset_identity"


def upgrade(conn: Connection) -> None:
    if conn.dialect.name != "postgresql":
        return

    target = conn.execute(text("""
        SELECT c.oid, n.nspname, c.relname
        FROM pg_catalog.pg_class c
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        WHERE c.oid = pg_catalog.to_regclass('structured_datasets')
          AND c.relkind = 'r'
    """)).one_or_none()
    if target is None:
        return

    oid, schema, name = target
    quote = conn.dialect.identifier_preparer.quote_identifier
    qualified = f"{quote(schema)}.{quote(name)}"
    # Serialize the check/DDL and block inserts while choosing the next ID.
    conn.execute(text(f"LOCK TABLE {qualified} IN ACCESS EXCLUSIVE MODE"))
    column = conn.execute(text("""
        SELECT a.attidentity, pg_catalog.pg_get_expr(d.adbin, d.adrelid)
        FROM pg_catalog.pg_attribute a
        LEFT JOIN pg_catalog.pg_attrdef d
          ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = :oid AND a.attname = 'id'
          AND a.attnum > 0 AND NOT a.attisdropped
    """), {"oid": oid}).one()
    identity, default = column
    if identity or default is not None:
        return

    conn.execute(text(
        f"ALTER TABLE {qualified} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"
    ))
    sequence = conn.execute(text(
        "SELECT pg_catalog.pg_get_serial_sequence(:table, 'id')"
    ), {"table": qualified}).scalar_one()
    if sequence is None:
        raise RuntimeError("Dataset identity sequence was not created")
    maximum = conn.execute(text(f"SELECT max(id) FROM {qualified}")).scalar_one()
    if maximum is not None:
        # false means the next nextval returns exactly max+1, not max+2.
        conn.execute(text(
            "SELECT pg_catalog.setval(CAST(:sequence AS regclass), :next_id, false)"
        ), {"sequence": sequence, "next_id": max(1, maximum + 1)})