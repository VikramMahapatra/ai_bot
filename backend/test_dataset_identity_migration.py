"""Offline bootstrap/repair regression tests: no configured DB or startup IO."""
import importlib.util
from pathlib import Path
import sys
import types
import unittest
from unittest.mock import Mock, patch

from sqlalchemy import Column, Integer, String, Table, create_engine, create_mock_engine
from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.orm import declarative_base
from sqlalchemy.schema import CreateTable

ROOT = Path(__file__).resolve().parent


def load_file(name, relative):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class DatasetIdentityTests(unittest.TestCase):
    def models(self):
        database = types.ModuleType("app.database")
        database.Base = declarative_base()
        with patch.dict(sys.modules, {"app.database": database}):
            models = load_file("_identity_models", "app/models/structured_dataset.py")
        Table("organizations", database.Base.metadata, Column("id", Integer, primary_key=True))
        Table("widget_configs", database.Base.metadata, Column("widget_id", String, primary_key=True))
        return models, database.Base

    def test_actual_bootstrap_create_all_emits_identity_despite_circular_fk(self):
        models, base = self.models()
        statements = []
        engine = create_mock_engine("postgresql://", lambda ddl, *a, **k:
                                   statements.append(str(ddl.compile(dialect=postgresql.dialect()))))
        # Exercise early Base.metadata.create_all, not just owned_metadata DDL.
        base.metadata.create_all(engine)
        ddl = next(s for s in statements if "CREATE TABLE structured_datasets (" in s)
        self.assertIn("id INTEGER GENERATED BY DEFAULT AS IDENTITY", ddl)
        self.assertEqual(models.StructuredDataset.__table__.c.id.autoincrement, "ignore_fk")
        self.assertTrue(any("ADD CONSTRAINT fk_sd_active_scope" in s for s in statements))

    def test_owned_metadata_and_sqlite_compatibility(self):
        models, base = self.models()
        ddl = str(CreateTable(models.owned_metadata().tables["structured_datasets"]).compile(
            dialect=postgresql.dialect()))
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", ddl)
        ddl = str(CreateTable(models.StructuredDataset.__table__).compile(dialect=sqlite.dialect()))
        self.assertNotIn("IDENTITY", ddl)
        engine = create_engine("sqlite:///:memory:")
        try:
            base.metadata.create_all(engine)
            with engine.begin() as conn:
                result = conn.execute(models.StructuredDataset.__table__.insert().values(
                    organization_id=1, widget_id="agent", name="Test"))
                self.assertEqual(result.inserted_primary_key, (1,))
        finally:
            engine.dispose()

    def migration(self):
        return load_file("_identity_repair", "app/migrations/m2026_10_14_repair_dataset_identity.py")

    def connection(self, identity="", default=None, maximum=None):
        conn = Mock()
        conn.dialect = postgresql.dialect()
        conn.execute.side_effect = [
            Mock(one_or_none=Mock(return_value=(42, 'owned"schema', "structured_datasets"))),
            Mock(), Mock(one=Mock(return_value=(identity, default))), Mock(),
            Mock(scalar_one=Mock(return_value='"owned""schema".structured_datasets_id_seq')),
            Mock(scalar_one=Mock(return_value=maximum)), Mock(),
        ]
        return conn

    def test_empty_repair_is_additive_and_schema_qualified(self):
        conn = self.connection()
        self.migration().upgrade(conn)
        sql = [str(call.args[0]) for call in conn.execute.call_args_list]
        self.assertEqual(len(sql), 6)
        self.assertIn('LOCK TABLE "owned""schema"."structured_datasets"', sql[1])
        self.assertIn("ADD GENERATED BY DEFAULT AS IDENTITY", sql[3])
        self.assertIn("pg_get_serial_sequence", sql[4])
        self.assertFalse(any("setval" in s for s in sql))
        self.assertFalse(any(word in s.upper() for s in sql for word in ("DROP ", "UPDATE ", "DELETE ")))

    def test_populated_repair_sets_next_id_without_changing_rows(self):
        conn = self.connection(maximum=23)
        self.migration().upgrade(conn)
        call = conn.execute.call_args_list[-1]
        self.assertIn("false", str(call.args[0]))
        self.assertEqual(call.args[1]["next_id"], 24)

    def test_existing_identity_or_default_is_untouched_on_rerun(self):
        for identity, default in [("d", None), ("a", None), ("", "nextval('existing_seq')")]:
            with self.subTest(identity=identity, default=default):
                conn = self.connection(identity=identity, default=default)
                self.migration().upgrade(conn)
                self.assertEqual(conn.execute.call_count, 3)

    def test_non_postgres_and_missing_table_are_noops(self):
        conn = Mock(dialect=sqlite.dialect())
        self.migration().upgrade(conn)
        conn.execute.assert_not_called()
        conn = Mock(dialect=postgresql.dialect())
        conn.execute.return_value.one_or_none.return_value = None
        self.migration().upgrade(conn)
        self.assertEqual(conn.execute.call_count, 1)

    def test_missing_sequence_fails_before_ledger_can_be_recorded(self):
        conn = self.connection()
        responses = list(conn.execute.side_effect)
        responses[4].scalar_one.return_value = None
        conn.execute.side_effect = responses
        with self.assertRaisesRegex(RuntimeError, "sequence was not created"):
            self.migration().upgrade(conn)


if __name__ == "__main__":
    unittest.main()